import fs from 'node:fs';
const F = 'node_modules/@fontsource/inter/files';
const M = 'node_modules/@fontsource/jetbrains-mono/files';
const out = ['/* Slash Tech Social — embedded typefaces. Generated by tooling/make-fonts.mjs */'];
const face = (fam, file, weight) => {
  const b = fs.readFileSync(file).toString('base64');
  return `@font-face{font-family:'${fam}';font-style:normal;font-display:block;font-weight:${weight};src:url(data:font/woff2;charset=utf-8;base64,${b}) format('woff2');}`;
};
for (const w of [400,500,600,700,800]) {
  out.push(face('Inter', `${F}/inter-latin-${w}-normal.woff2`, w));
  out.push(face('Inter', `${F}/inter-latin-ext-${w}-normal.woff2`, w));
}
for (const w of [400,500,700]) {
  out.push(face('JetBrains Mono', `${M}/jetbrains-mono-latin-${w}-normal.woff2`, w));
}
fs.writeFileSync('../design-system/fonts/fonts.css', out.join('\n') + '\n');
console.log('fonts.css', (fs.statSync('../design-system/fonts/fonts.css').size/1024).toFixed(0)+'KB');
